import { randomUUID } from "node:crypto";
import { mkdir, unlink, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

export const GUIDE_UPLOAD_DIR = fileURLToPath(new URL("../../uploads/guides/", import.meta.url));
export const MAX_PDF_SIZE = 10 * 1024 * 1024;
const localPattern = /^\/uploads\/guides\/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.pdf)$/;

export async function saveGuideFile(file) {
    await mkdir(GUIDE_UPLOAD_DIR, { recursive: true });
    const filename = `${randomUUID()}.pdf`;
    const filePath = path.join(GUIDE_UPLOAD_DIR, filename);
    try {
        await writeFile(filePath, file.buffer, { flag: "wx" });
    } catch (error) {
        if (error.code !== "EEXIST") await unlink(filePath).catch(() => {});
        throw error;
    }
    return `/uploads/guides/${filename}`;
}

// Only paths generated by this upload service are eligible for removal.
// Absolute/external URLs and arbitrary filesystem paths are never followed.
export async function removeGuideFile(fileUrl) {
    const match = typeof fileUrl === "string" && fileUrl.match(localPattern);
    if (!match) return;
    try {
        await unlink(path.join(GUIDE_UPLOAD_DIR, match[1]));
    } catch (error) {
        if (error.code !== "ENOENT") console.error("Gagal membersihkan file panduan:", error);
    }
}

export function guideForResponse(guide, req) {
    if (!guide || !localPattern.test(guide.fileUrl ?? "")) return guide;
    return { ...guide, fileUrl: `${req.protocol}://${req.get("host")}${guide.fileUrl}` };
}
